#!/usr/bin/env bash
#
# Prepares a fresh Ubuntu 22.04/24.04 VPS to run the Blue ID register.
#
#   scp -r deploy/ root@<server>:/tmp/blueid-deploy
#   ssh root@<server> 'bash /tmp/blueid-deploy/provision.sh'
#
# Everything runs natively: PostgreSQL from the Ubuntu archive, Node from
# NodeSource, the API under systemd, nginx in front. No containers.
#
# The reason is maintenance rather than taste. Postgres installed from apt is
# patched by unattended-upgrades the night a CVE lands; a pinned container
# image keeps running the vulnerable version until somebody remembers to
# rebuild it. This register will sit on this server for years, so the thing
# that patches itself is the thing to choose.
#
# Idempotent: safe to re-run. It prepares the machine and stops short of
# anything involving a secret, because those should not be generated by a
# script that also prints them.

set -euo pipefail

SERVICE_USER="blueid"
APP_DIR="/opt/blueid"
DATA_DIR="/var/lib/blueid"
MEDIA_DIR="${DATA_DIR}/media"
BACKUP_DIR="/var/backups/blueid"
PG_VERSION="16"
NODE_MAJOR="22"
DB_NAME="blueid"
DB_USER="blueid"

log()  { printf '\n\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }

if [[ $EUID -ne 0 ]]; then
  echo "Run as root: sudo bash $0" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
log "Base packages"
# ---------------------------------------------------------------------------
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq \
  ca-certificates curl gnupg lsb-release \
  nginx certbot python3-certbot-nginx \
  restic ufw fail2ban unattended-upgrades \
  build-essential

# ---------------------------------------------------------------------------
log "PostgreSQL ${PG_VERSION} with PostGIS"
# ---------------------------------------------------------------------------
# The PostgreSQL Global Development Group archive. Ubuntu 24.04 ships 16 but
# 22.04 ships 14, so pinning a version without this makes the script work on
# one release and fail on the other. PGDG also keeps security updates coming
# for the pinned major after the Ubuntu release stops tracking it.
if [[ ! -f /etc/apt/sources.list.d/pgdg.list ]]; then
  install -d /etc/apt/keyrings
  curl -fsSL https://www.postgresql.org/media/keys/ACCC4CF8.asc \
    | gpg --dearmor -o /etc/apt/keyrings/pgdg.gpg
  chmod a+r /etc/apt/keyrings/pgdg.gpg
  echo "deb [signed-by=/etc/apt/keyrings/pgdg.gpg] https://apt.postgresql.org/pub/repos/apt $(lsb_release -cs)-pgdg main" \
    > /etc/apt/sources.list.d/pgdg.list
  apt-get update -qq
fi

# PostGIS comes from the same archive as Postgres, so both are covered by
# unattended-upgrades. One package, no compiling.
apt-get install -y -qq \
  "postgresql-${PG_VERSION}" \
  "postgresql-client-${PG_VERSION}" \
  "postgresql-${PG_VERSION}-postgis-3" \
  "postgresql-contrib-${PG_VERSION}"

systemctl enable --now postgresql

PGCONF="/etc/postgresql/${PG_VERSION}/main/postgresql.conf"
PGHBA="/etc/postgresql/${PG_VERSION}/main/pg_hba.conf"

# Listen on loopback only. The API is on this same host, so the database has
# no reason to be reachable from the network — and a database that is not
# listening cannot be attacked from outside.
sed -i "s/^#\?listen_addresses.*/listen_addresses = 'localhost'/" "$PGCONF"

# Tuning for an 8GB / 4 vCPU box. Scale shared_buffers to ~25% of RAM and
# effective_cache_size to ~60% if the server is larger.
TOTAL_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
SHARED_MB=$(( TOTAL_MB / 4 ))
CACHE_MB=$(( TOTAL_MB * 3 / 5 ))

apply_setting() {
  local key="$1" value="$2"
  if grep -qE "^#?\s*${key}\s*=" "$PGCONF"; then
    sed -i "s|^#\?\s*${key}\s*=.*|${key} = ${value}|" "$PGCONF"
  else
    echo "${key} = ${value}" >> "$PGCONF"
  fi
}

apply_setting shared_buffers            "${SHARED_MB}MB"
apply_setting effective_cache_size      "${CACHE_MB}MB"
apply_setting work_mem                  "16MB"
apply_setting maintenance_work_mem      "512MB"
apply_setting max_connections           "100"
apply_setting wal_level                 "replica"
apply_setting max_wal_size              "2GB"
# Anything slower than half a second is worth looking at.
apply_setting log_min_duration_statement "500"
apply_setting log_checkpoints            "on"
apply_setting log_line_prefix            "'%m [%p] %q%u@%d '"

systemctl restart postgresql

# Data checksums catch silent disk corruption, which for a register that
# cannot be re-collected is worth a few percent of write overhead. They can
# only be chosen when the cluster is created, NOT in postgresql.conf — it is
# a read-only parameter and setting it there stops the server starting. So
# the cluster is recreated, and only while it is still empty.
CHECKSUMS=$(sudo -u postgres psql -tAc "SHOW data_checksums" 2>/dev/null || echo "off")
if [[ "$CHECKSUMS" != "on" ]]; then
  HAS_DB=$(sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='${DB_NAME}'" 2>/dev/null || true)
  if [[ -z "$HAS_DB" ]]; then
    warn "Recreating the cluster with data checksums (it is still empty)"
    pg_dropcluster --stop "$PG_VERSION" main
    pg_createcluster --start -- --data-checksums "$PG_VERSION" main
    systemctl restart postgresql
  else
    warn "Cluster has no data checksums and already holds ${DB_NAME}; leaving it alone."
    warn "Enabling them later needs pg_checksums with the cluster stopped."
  fi
fi

# ---------------------------------------------------------------------------
log "Database and role"
# ---------------------------------------------------------------------------
# The password is NOT set here. Peer authentication over the local socket
# means the service user connects without one, so there is no database
# password to leak, rotate or find in a process list.
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='${DB_USER}'" | grep -q 1; then
  sudo -u postgres createuser "$DB_USER"
fi
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='${DB_NAME}'" | grep -q 1; then
  sudo -u postgres createdb -O "$DB_USER" "$DB_NAME"
fi

# The extensions the schema declares. Created here as superuser because
# CREATE EXTENSION needs it; the migration then finds them already present.
sudo -u postgres psql -d "$DB_NAME" -qc "CREATE EXTENSION IF NOT EXISTS pgcrypto;"
sudo -u postgres psql -d "$DB_NAME" -qc "CREATE EXTENSION IF NOT EXISTS postgis;"
sudo -u postgres psql -d "$DB_NAME" -qc "CREATE EXTENSION IF NOT EXISTS pg_trgm;"
sudo -u postgres psql -d "$DB_NAME" -tc "SELECT 'postgis ' || postgis_version();" | sed 's/^/    /'

# ---------------------------------------------------------------------------
log "Node ${NODE_MAJOR}"
# ---------------------------------------------------------------------------
if ! command -v node >/dev/null 2>&1 || [[ "$(node -v | cut -c2-3)" != "$NODE_MAJOR" ]]; then
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash -
  apt-get install -y -qq nodejs
fi
node --version | sed 's/^/    node /'

# ---------------------------------------------------------------------------
log "Service user and data directories"
# ---------------------------------------------------------------------------
if ! id -u "$SERVICE_USER" >/dev/null 2>&1; then
  useradd --system --create-home --shell /usr/sbin/nologin "$SERVICE_USER"
fi

# Outside APP_DIR on purpose: a redeploy must never be able to delete the
# photographs. They cannot be regenerated — losing one means sending an
# enumerator back to the fisherman.
install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0750 "$DATA_DIR" "$MEDIA_DIR" "$BACKUP_DIR"
install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0750 "$APP_DIR"

# nginx reads the photographs directly via X-Accel-Redirect, so it needs to
# traverse the media directory.
usermod -aG "$SERVICE_USER" www-data

# ---------------------------------------------------------------------------
log "systemd unit"
# ---------------------------------------------------------------------------
cat > /etc/systemd/system/blueid.service <<UNIT
[Unit]
Description=Cross River State Blue ID API
Documentation=file://${APP_DIR}/OPERATIONS.md
After=network-online.target postgresql.service
Wants=network-online.target
Requires=postgresql.service

[Service]
Type=simple
User=${SERVICE_USER}
Group=${SERVICE_USER}
WorkingDirectory=${APP_DIR}
# No EnvironmentFile on purpose. The application reads ${APP_DIR}/.env itself
# through dotenv, which strips inline comments; systemd's parser does not, so
# it would read "secret   # GENERATE" as the secret. One loader, one format.
Environment=NODE_ENV=production
ExecStart=/usr/bin/node ${APP_DIR}/src/server.js

Restart=always
RestartSec=5
# Give a long export time to drain before SIGKILL.
TimeoutStopSec=30
KillSignal=SIGTERM

StandardOutput=journal
StandardError=journal
SyslogIdentifier=blueid

# The API needs the network, its own data directory and nothing else.
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
RestrictNamespaces=true
LockPersonality=true
MemoryDenyWriteExecute=false
ReadWritePaths=${DATA_DIR}

[Install]
WantedBy=multi-user.target
UNIT

systemctl daemon-reload
systemctl enable blueid.service >/dev/null

# ---------------------------------------------------------------------------
log "Firewall"
# ---------------------------------------------------------------------------
ufw --force reset >/dev/null
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow OpenSSH >/dev/null
ufw allow 80/tcp  >/dev/null   # certbot's HTTP-01 challenge and the redirect
ufw allow 443/tcp >/dev/null
# 5432 is deliberately absent, and Postgres listens on loopback anyway.
# To reach the database:  ssh -L 5432:127.0.0.1:5432 <server>
ufw --force enable >/dev/null
ufw status | sed 's/^/    /'

systemctl enable --now fail2ban

# ---------------------------------------------------------------------------
log "nginx site"
# ---------------------------------------------------------------------------
read -rp "    Domain for this server (e.g. blueid.crossriverstate.gov.ng): " DOMAIN
DOMAIN="${DOMAIN:-_}"

cat > /etc/nginx/sites-available/blueid <<NGINX
# Blue ID — TLS termination and photograph delivery.

upstream blueid_api {
    server 127.0.0.1:4000;
    keepalive 32;
}

server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN};
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${DOMAIN};

    # certbot fills these in.
    # ssl_certificate     /etc/letsencrypt/live/${DOMAIN}/fullchain.pem;
    # ssl_certificate_key /etc/letsencrypt/live/${DOMAIN}/privkey.pem;

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # A day of field photographs can arrive in one sync.
    client_max_body_size 12m;

    # Photographs. INTERNAL: nginx will not serve this to a client directly.
    # The app checks the signed URL, then returns an X-Accel-Redirect pointing
    # here — so the bytes are sent by nginx and never pass through the Node
    # event loop. Set MEDIA_XACCEL_PREFIX=/protected-media to enable it.
    location /protected-media/ {
        internal;
        alias ${MEDIA_DIR}/;
        add_header Cache-Control "private, max-age=300" always;
        add_header X-Content-Type-Options "nosniff" always;
    }

    location / {
        proxy_pass         http://blueid_api;
        proxy_http_version 1.1;
        proxy_set_header   Host              \$host;
        proxy_set_header   X-Real-IP         \$remote_addr;
        proxy_set_header   X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto \$scheme;
        proxy_set_header   Connection        "";
        # Long enough for a streamed Excel export of the whole register.
        proxy_read_timeout 300s;
    }
}
NGINX

ln -sf /etc/nginx/sites-available/blueid /etc/nginx/sites-enabled/blueid
rm -f /etc/nginx/sites-enabled/default
nginx -t && systemctl reload nginx

# ---------------------------------------------------------------------------
log "Backups"
# ---------------------------------------------------------------------------
# Two halves. A nightly dump to local disk, and a job that ships the dump and
# the photographs off this machine. Only the second half survives the disk
# failing, which is the scenario that ends the project.
cat > /usr/local/bin/blueid-dump <<DUMP
#!/usr/bin/env bash
set -euo pipefail
STAMP=\$(date -u +%Y%m%dT%H%M%SZ)
umask 077
pg_dump -U ${DB_USER} -d ${DB_NAME} --format=custom --compress=6 \\
  --file="${BACKUP_DIR}/blueid-\${STAMP}.dump"
# Keep 14 locally; the off-box copy carries the real retention.
ls -1t ${BACKUP_DIR}/blueid-*.dump 2>/dev/null | tail -n +15 | xargs -r rm -f
DUMP
chmod 0750 /usr/local/bin/blueid-dump
chown root:"$SERVICE_USER" /usr/local/bin/blueid-dump

cat > /usr/local/bin/blueid-backup <<'BACKUP'
#!/usr/bin/env bash
set -euo pipefail
# Ships the nightly dump and the photographs off this machine.
# Point RESTIC_REPOSITORY at storage inside Nigeria: NITDA's guidance puts
# the disaster-recovery copy under the same residency rule as the primary.
source /etc/blueid/backup.env
restic backup /var/backups/blueid /var/lib/blueid/media --tag blueid --exclude-caches
restic forget --tag blueid --keep-daily 14 --keep-weekly 8 --keep-monthly 12 --prune
restic check --read-data-subset=5%
BACKUP
chmod 0750 /usr/local/bin/blueid-backup

install -d -m 0700 /etc/blueid
if [[ ! -f /etc/blueid/backup.env ]]; then
  cat > /etc/blueid/backup.env <<'ENVFILE'
# Fill in, then: systemctl enable --now blueid-backup.timer
# export RESTIC_REPOSITORY="s3:https://<in-country-endpoint>/blueid-backup"
# export RESTIC_PASSWORD="..."
# export AWS_ACCESS_KEY_ID="..."
# export AWS_SECRET_ACCESS_KEY="..."
ENVFILE
  chmod 0600 /etc/blueid/backup.env
fi

write_timer() {
  local name="$1" desc="$2" exec="$3" when="$4" user="$5"
  cat > "/etc/systemd/system/${name}.service" <<UNIT
[Unit]
Description=${desc}
After=network-online.target postgresql.service

[Service]
Type=oneshot
User=${user}
ExecStart=${exec}
UNIT
  cat > "/etc/systemd/system/${name}.timer" <<UNIT
[Unit]
Description=${desc}

[Timer]
OnCalendar=${when}
RandomizedDelaySec=900
Persistent=true

[Install]
WantedBy=timers.target
UNIT
}

write_timer blueid-dump   "Blue ID nightly database dump" /usr/local/bin/blueid-dump   "*-*-* 02:00:00" "$SERVICE_USER"
write_timer blueid-backup "Blue ID off-box backup"        /usr/local/bin/blueid-backup "*-*-* 02:30:00" root

systemctl daemon-reload
systemctl enable --now blueid-dump.timer >/dev/null

# ---------------------------------------------------------------------------
log "Automatic security updates"
# ---------------------------------------------------------------------------
dpkg-reconfigure -f noninteractive unattended-upgrades >/dev/null 2>&1 || true

# ---------------------------------------------------------------------------
log "Prepared. The remaining steps involve secrets, so they are manual."
# ---------------------------------------------------------------------------
cat <<NEXT

    1. Put the application on the server
         rsync -a --exclude node_modules --exclude .git ./ root@<server>:${APP_DIR}/
         chown -R ${SERVICE_USER}:${SERVICE_USER} ${APP_DIR}

    2. Install production dependencies
         sudo -u ${SERVICE_USER} bash -c 'cd ${APP_DIR} && npm ci --omit=dev'

    3. Create the environment file and fill in every GENERATE value
         cp ${APP_DIR}/deploy/.env.production.example ${APP_DIR}/.env
         chown ${SERVICE_USER}:${SERVICE_USER} ${APP_DIR}/.env
         chmod 600 ${APP_DIR}/.env
         # for each secret: openssl rand -base64 48

       DATABASE_URL needs no password — the service user connects over the
       local socket with peer authentication:
         DATABASE_URL=postgres://${DB_USER}@/${DB_NAME}?host=/var/run/postgresql

    4. Create the schema
         sudo -u ${SERVICE_USER} bash -c 'cd ${APP_DIR} && npm run db:migrate'

    5. Start it
         systemctl start blueid && systemctl status blueid --no-pager

    6. Create the first administrator — the password prints once
         sudo -u ${SERVICE_USER} bash -c 'cd ${APP_DIR} && \\
           node src/scripts/createAdmin.js --role=SUPER_ADMIN \\
             --email=<address> --first=<name> --last=<name>'

    7. Issue the TLS certificate
         certbot --nginx -d ${DOMAIN}

    8. Configure and enable the off-box backup — DO NOT SKIP
         edit /etc/blueid/backup.env
         systemctl enable --now blueid-backup.timer
         systemctl start blueid-backup.service    # prove it works now
         restic -r <repo> snapshots               # confirm a snapshot exists

    9. Book a restore drill for next month. An untested backup is not a
       backup, and the photographs cannot be re-collected.

NEXT

warn "Postgres listens on loopback only and the firewall does not open 5432."
echo "      To connect:  ssh -L 5432:127.0.0.1:5432 <server>"
